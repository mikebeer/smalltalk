#!/usr/bin/env python3
"""Generate src/s_gen.h from ../src/{consts,selectors,prims}.txt (run by hand, result is checked in)."""
import os
here = os.path.dirname(os.path.abspath(__file__))
srcdir = os.path.join(here, '..', '..', 'src')
out = ['/* generated by tools/gen_consts.py - do not edit */']
for line in open(os.path.join(srcdir, 'consts.txt')):
    line = line.rstrip('\n')
    if not line or line.startswith('#'):
        continue
    n, v = line.split(None, 1)
    out.append('#define %s %s' % (n, v.strip()))
sels = []
for line in open(os.path.join(srcdir, 'selectors.txt')):
    line = line.rstrip('\n')
    if not line:
        continue
    n, v = line.split(None, 1)
    sels.append((n, v.strip()))
for i, (n, v) in enumerate(sels):
    out.append('#define %s %d' % (n, i + 1))
out.append('#define NSPECIAL %d' % len(sels))
out.append('static const char *const special_sels[] = {')
for n, v in sels:
    out.append('    "%s",' % v.replace('\\', '\\\\').replace('"', '\\"'))
out.append('    0');
out.append('};')
prims = []
for line in open(os.path.join(srcdir, 'prims.txt')):
    line = line.strip()
    if not line:
        continue
    n, v = line.split()
    prims.append((n, v))
for i, (n, v) in enumerate(prims):
    out.append('#define %s %d' % (n, i + 1))
out.append('static const char *const prim_names[] = {')
out.append('    "",')
for n, v in prims:
    out.append('    "%s",' % v)
out.append('    0')
out.append('};')
open(os.path.join(here, '..', 'src', 's_gen.h'), 'w').write('\n'.join(out) + '\n')
